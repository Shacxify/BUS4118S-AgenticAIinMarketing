"""Scripted demo for the submission:  python -m supplychain.demo

Conversation A runs 5 turns on one thread and hops between all three specialist agents; later turns
only work because MemorySaver kept the earlier ones ("that shipment", "the faster one" and the PO
numbers are never spelled out again). Conversation B is a new thread_id, showing memory is per
conversation. Writes supplychain/outputs/demo_transcript.md and supplychain/outputs/graph.mmd.
"""
import time
from pathlib import Path

from chatbot.chat import ask

from .graph import build_graph

OUT = Path(__file__).resolve().parent / "outputs"
PAUSE = 20  # seconds between turns: a turn can make 4-5 Gemini calls and the free tier allows 15 per minute

CONVERSATIONS = {
    "ops-morning": [
        "Morning Atlas. How are we looking on Brazil Cerrado green coffee? Are we going to run out?",
        "That Brazil shipment, is it still on schedule? What's going on with it?",
        "We can't miss house blend orders. Who can get us enough Brazil to bridge the gap, and what will it cost?",
        "Go with the fastest option. Place an order for 500 lb.",
        "Quick recap for my notes: the new PO number, when it lands, and when the delayed shipment arrives.",
    ],
    "new-shift": [
        "When does my PO arrive?",
    ],
}


def main():
    OUT.mkdir(exist_ok=True)
    graph = build_graph()
    (OUT / "graph.mmd").write_text(graph.get_graph().draw_mermaid(), encoding="utf-8")

    md = ["# Demo transcript: Ridgeline Coffee Co. supply chain assistant", "",
          "Generated by `python -m supplychain.demo` (live Gemini calls, LangGraph `MemorySaver`).", ""]
    for thread_id, turns in CONVERSATIONS.items():
        md += [f"## Conversation `thread_id={thread_id}`", ""]
        print(f"\n=== thread_id={thread_id} ===")
        for n, text in enumerate(turns, 1):
            reply, route, tools = ask(graph, thread_id, text)
            saved = len(graph.get_state({"configurable": {"thread_id": thread_id}}).values["messages"])
            tool_note = ", ".join(f"`{t}`" for t in tools) or "none"
            print(f"\n[turn {n}] You: {text}\n[{route} agent | tools: {', '.join(tools) or 'none'} | "
                  f"{saved} messages in memory]\nAtlas: {reply}")
            md += [f"**Turn {n}. Ops manager:** {text}", "",
                   f"*Routed to:* `{route}` agent · *Tools:* {tool_note} · *Messages saved in thread:* {saved}", "",
                   f"**Atlas:** {reply}", ""]
            time.sleep(PAUSE)
    (OUT / "demo_transcript.md").write_text("\n".join(md), encoding="utf-8")
    print(f"\nWrote {OUT / 'demo_transcript.md'} and {OUT / 'graph.mmd'}")


if __name__ == "__main__":
    main()
