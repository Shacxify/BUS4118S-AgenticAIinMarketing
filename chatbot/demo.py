"""Scripted demo for the submission:  python -m chatbot.demo

Conversation A runs 5 turns on one thread and hops between all three specialist agents; later turns
only work because MemorySaver kept the earlier ones (the order number and the disliked roast are
never repeated). Conversation B is a new thread_id, showing memory is per conversation.
Writes chatbot/outputs/demo_transcript.md and chatbot/outputs/graph.mmd.
"""
import time
from pathlib import Path

from .chat import ask
from .graph import build_graph

OUT = Path(__file__).resolve().parent / "outputs"
PAUSE = 4   # seconds between turns, to stay under free-tier requests-per-minute limits

CONVERSATIONS = {
    "maya-session": [
        "Hi! Can you check on my order RC-1001?",
        "Thanks. I opened one of the Sumatra bags and honestly it's too earthy for me. Can I get my money back?",
        "Yes please, go ahead and start that for the Sumatra.",
        "What should I try instead? I brew pour-over and like brighter, fruity coffee. Ideally under $20.",
        "Quick recap before I go: what was my order number, and what's my return ID?",
    ],
    "new-visitor": [
        "What's my order number?",
    ],
}


def main():
    OUT.mkdir(exist_ok=True)
    graph = build_graph()
    (OUT / "graph.mmd").write_text(graph.get_graph().draw_mermaid(), encoding="utf-8")

    md = ["# Demo transcript: Ridgeline Coffee Co. assistant", "",
          "Generated by `python -m chatbot.demo` (live Gemini calls, LangGraph `MemorySaver`).", ""]
    for thread_id, turns in CONVERSATIONS.items():
        md += [f"## Conversation `thread_id={thread_id}`", ""]
        print(f"\n=== thread_id={thread_id} ===")
        for n, text in enumerate(turns, 1):
            reply, route, tools = ask(graph, thread_id, text)
            saved = len(graph.get_state({"configurable": {"thread_id": thread_id}}).values["messages"])
            tool_note = ", ".join(f"`{t}`" for t in tools) or "none"
            print(f"\n[turn {n}] You: {text}\n[{route} agent | tools: {', '.join(tools) or 'none'} | "
                  f"{saved} messages in memory]\nRidge: {reply}")
            md += [f"**Turn {n}. Customer:** {text}", "",
                   f"*Routed to:* `{route}` agent · *Tools:* {tool_note} · *Messages saved in thread:* {saved}", "",
                   f"**Ridge:** {reply}", ""]
            time.sleep(PAUSE)
    (OUT / "demo_transcript.md").write_text("\n".join(md), encoding="utf-8")
    print(f"\nWrote {OUT / 'demo_transcript.md'} and {OUT / 'graph.mmd'}")


if __name__ == "__main__":
    main()
